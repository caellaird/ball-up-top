export const STATE_NAME_BY_CODE = US_STATES.reduce((acc, s) => {
  acc[s.code] = s.name;
  return acc;
}, {});

// Splits a stored profile location ("Durham, NC") into city text + state code.
export function splitProfileLocation(profile) {
  const display = (profile?.city_display || profile?.city || '').toString().trim();
  const parts = display.split(',').map((p) => p.trim()).filter(Boolean);
  const city = parts[0] || '';
  let stateCode = (profile?.state_code || '').toString().trim().toUpperCase();
  if (!stateCode && STATE_NAME_BY_CODE[parts[1]?.toUpperCase()]) {
    stateCode = parts[1].toUpperCase();
  }
  return { city, stateCode };
}